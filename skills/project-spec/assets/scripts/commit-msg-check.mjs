/**
 * 提交信息校验 + 文档同步检查（纯函数 + CLI），由 scripts/hooks/commit-msg 调用。
 *
 * 约定见 AGENTS.md「工作流约定 · 提交信息 / 文档同步」：
 *   - 标题（首行）≤ MAX_SUBJECT_LENGTH 字符（含「功能:」类前缀），超出即拒绝提交；
 *   - 标题必须以 PREFIXES 白名单里的前缀开头；
 *   - 细节一律写进 CHANGELOG.md，提交不留长正文（正文非空只提示、不阻断）；
 *   - 暂存区命中 DOC_SYNC_RULES 里某条规则的文件而该规则要求的文档未同步时拒绝提交，
 *     豁免走正文 DOC_SYNC_MARKER 标记（随提交入库、可 grep）或 git commit --no-verify。
 *
 * 为什么校验逻辑在 Node 而不是直接写在钩子脚本里：长度按「字符」计（一个汉字算 1），
 * 而 shell 的字符串长度与 wc -c 在 UTF-8 下按字节算，中文标题会被算成 3 倍而全部误判。
 * 改下面这些常量时，必须同步改 AGENTS.md 里写的那份——两处不一致时以本文件为准，
 * 因为它才是真正拦住提交的那一道。
 */
import { readFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { execFileSync } from 'node:child_process'

/** 标题长度上限（字符数，按 Unicode 码点计） */
export const MAX_SUBJECT_LENGTH = 30

/** 允许的标题前缀，与 AGENTS.md 的白名单同步维护 */
export const PREFIXES = ['功能', '修复', '优化', '重构', '清理', '文档', '测试', '构建', '发版']

/**
 * 文档同步规则：命中 files 的暂存改动必须同步 doc，否则拒绝提交。
 * 按仓库根（git 输出的正斜杠路径）匹配，一条不满足就单独报出来。
 *
 * files 只写根文件与目录级模式，不写具体业务文件名或端点路径——本脚本要拷进任何项目，
 * 清单里出现某个项目自己的名字，换一个项目就成了误拦。规则按项目实际增删。
 */
export const DOC_SYNC_RULES = [
  {
    doc: 'README.md',
    // 这些文件决定 README 的「环境要求 / 快速开始 / 常用命令」是否还成立
    files: [
      'package.json',
      'pnpm-workspace.yaml',
      '.env.example',
      /^[\w@][\w.-]*\.config\.[cm]?[jt]sx?$/, // 根目录构建/工具配置：vite.config.ts、eslint.config.js…
      /^tsconfig[\w.-]*\.json$/, // tsconfig.json 与 tsconfig.node.json 等派生
    ],
    why: 'README 的「环境要求 / 快速开始 / 常用命令」由这些文件决定',
  },
  {
    doc: 'docs/DEPLOY.md',
    // 服务端路由与前端请求封装：两者的对外行为都由这一张码表描述
    files: [/^server\//, /^src\/api\//],
    why: '「接口错误码」表是前后端唯一的码表来源，新增或改动端点必须同步那一节',
  },
]

/** 提交正文携带此标记 = 显式声明本次无需同步文档；标记随提交入库，git log 里可 grep 审计 */
export const DOC_SYNC_MARKER = '[skip-docs]'

/** Git 自动生成的提交信息，不受本约定约束 */
const AUTOGENERATED = /^(Merge |Revert |fixup! |squash! )/

/**
 * 校验一条提交信息。
 * @param {string} raw 提交信息全文（含可能的注释行与正文）
 * @returns {{ok: boolean, exempt: boolean, subject: string, length: number, errors: string[], warnings: string[]}}
 */
export function checkCommitMessage(raw) {
  // 先剔除编辑器模板里的注释行（git 默认注释符 #），再取首个非空行为标题
  const lines = String(raw)
    .split(/\r?\n/)
    .filter((line) => !line.startsWith('#'))
  const subjectAt = lines.findIndex((line) => line.trim() !== '')
  const subject = subjectAt === -1 ? '' : lines[subjectAt].trim()
  const length = [...subject].length
  const errors = []
  const warnings = []

  if (AUTOGENERATED.test(subject)) {
    return { ok: true, exempt: true, subject, length, errors, warnings }
  }

  if (subject === '') {
    errors.push('标题为空')
  } else if (length > MAX_SUBJECT_LENGTH) {
    // 超长是最主要的失守形态，单独报字数，方便直接照着删
    errors.push(
      `标题 ${length} 字符，超出上限 ${MAX_SUBJECT_LENGTH} 字符——细节请写入 CHANGELOG.md，标题只留「改了什么」`,
    )
  } else {
    const matched = subject.match(/^([^:：]+)[:：]\s*(\S.*)$/)
    if (!matched) {
      errors.push(`标题需为「前缀: 说明」，可用前缀：${PREFIXES.join(' / ')}`)
    } else if (!PREFIXES.includes(matched[1])) {
      errors.push(`未知前缀「${matched[1]}」，可用前缀：${PREFIXES.join(' / ')}`)
    }
  }

  const body = lines.slice(subjectAt + 1).filter((line) => line.trim() !== '')
  if (body.length > 0) {
    warnings.push(`检测到 ${body.length} 行正文：细节统一写进 CHANGELOG.md，提交建议只留标题`)
  }

  return { ok: errors.length === 0, exempt: false, subject, length, errors, warnings }
}

/** 暂存文件是否落在某条规则的文件清单里（按正斜杠路径比较，精确名或正则） */
function ruleMatches(rule, path) {
  const normalized = String(path).replaceAll('\\', '/')
  return rule.files.some((pattern) =>
    typeof pattern === 'string' ? normalized === pattern : pattern.test(normalized),
  )
}

/**
 * 文档同步检查：逐条规则判断「命中该规则 files 的文件被改了，而该规则的 doc 没进暂存区」。
 * 规则之间互不豁免——只同步 README 不能放行一次改了服务端路由却没同步码表的提交。
 * 「重大调整」没法机械判断，清单只覆盖高置信子集；src/** 内部改动是否牵连文档属判断题，
 * 由 AGENTS.md 的文字规约约束同轮自查。
 *
 * @param {string[]|null} changedFiles 暂存区文件清单（git diff --cached --name-only）；
 *   null = 取不到（非 git 仓库、git 缺失等），此时降级为提示而不拦——检查器坏了不能堵死正常提交
 * @param {string} messageText 提交信息全文，用于识别 DOC_SYNC_MARKER 豁免标记
 * @returns {{blocked: boolean, reason: string|null, notices: string[]}}
 */
export function checkDocSync(changedFiles, messageText) {
  if (changedFiles === null) {
    return {
      blocked: false,
      reason: null,
      notices: ['未取得暂存区清单（非 git 仓库或 git 不可用），跳过文档同步检查'],
    }
  }

  const missed = []
  for (const rule of DOC_SYNC_RULES) {
    const hit = changedFiles.filter((file) => ruleMatches(rule, file))
    if (hit.length === 0 || changedFiles.includes(rule.doc)) continue
    missed.push({ doc: rule.doc, why: rule.why, files: hit })
  }
  if (missed.length === 0) {
    return { blocked: false, reason: null, notices: [] }
  }
  if (String(messageText).includes(DOC_SYNC_MARKER)) {
    return {
      blocked: false,
      reason: null,
      notices: [`信息含 ${DOC_SYNC_MARKER}，本次豁免文档同步检查（豁免已随提交入库）`],
    }
  }
  return {
    blocked: true,
    reason:
      missed
        .map((item) => `${item.files.join('、')} 改动但 ${item.doc} 未同步——${item.why}`)
        .join('；') +
      `；确无需同步时在提交正文单独一行写 ${DOC_SYNC_MARKER}（豁免可见、可 grep），或 git commit --no-verify`,
    notices: [],
  }
}

/** 取暂存区清单；任何失败（非 git 仓库、git 缺失）都返回 null，由 checkDocSync 降级为提示 */
function stagedFiles() {
  try {
    // 钩子由 git 在仓库根执行，但直接跑 CLI 时可能在子目录——统一显式定位仓库根
    const root = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim()
    // -z：文件名原样输出不做转义，按 \0 切；空仓库（无 HEAD）也能列出全部暂存文件
    const out = execFileSync('git', ['diff', '--cached', '--name-only', '-z'], {
      cwd: root,
      encoding: 'utf8',
    })
    return out.split('\0').filter((name) => name !== '')
  } catch {
    return null
  }
}

// CLI 入口：node scripts/commit-msg-check.mjs <提交信息文件>
// 退出码 0 = 通过（可能有警告）、1 = 不合规（钩子据此拒绝提交）、2 = 用法错误
const invokedDirectly =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href

if (invokedDirectly) {
  const file = process.argv[2]
  if (file === undefined) {
    console.error('用法: node scripts/commit-msg-check.mjs <提交信息文件>')
    process.exit(2)
  }

  const message = readFileSync(file, 'utf8')
  const result = checkCommitMessage(message)
  for (const warning of result.warnings) {
    console.warn(`[commit-msg] 提示：${warning}`)
  }

  if (!result.ok) {
    console.error('[commit-msg] 提交信息不合规：')
    for (const error of result.errors) {
      console.error(`  · ${error}`)
    }
    console.error('  约定见 AGENTS.md「工作流约定 · 提交信息」；确需绕过用 git commit --no-verify')
    process.exit(1)
  }

  // Merge/Revert 等自动提交不做文档同步检查——它们动什么不归作者挑
  if (!result.exempt) {
    const doc = checkDocSync(stagedFiles(), message)
    for (const notice of doc.notices) {
      console.warn(`[commit-msg] 提示：${notice}`)
    }
    if (doc.blocked) {
      console.error('[commit-msg] 文档同步检查未通过：')
      console.error(`  · ${doc.reason}`)
      console.error('  约定见 AGENTS.md「工作流约定 · 文档同步」')
      process.exit(1)
    }
  }

  process.exit(0)
}
